"""Execute all four parts of the course pickling exercise and save real outputs."""
import contextlib
import hashlib
import io
import json
import pickle
import platform
from pathlib import Path

import joblib
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import sklearn
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_squared_error, r2_score

from grade_tracker import GradeTracker

ROOT = Path(__file__).resolve().parent


def save_pickle(filename, value):
    with (ROOT / filename).open("wb") as handle:
        pickle.dump(value, handle, protocol=pickle.HIGHEST_PROTOCOL)


def load_pickle(filename):
    # All files loaded by this exercise were generated by this script.
    with (ROOT / filename).open("rb") as handle:
        return pickle.load(handle)


def run():
    print("Python Pickling Practice | LanMingqi | 26723811")
    print("All student names, grades, and study-hour observations below are example data.")
    print("\nPART 1: Regular Python data structures")
    fruits = ["apple", "banana", "mango", "strawberry"]
    scores = {"Alice": 92, "Bob": 85, "Charlie": 78, "Diana": 95}
    complex_data = {"fruits": fruits, "scores": scores,
                    "metrics": [1.2, 3.4, 5.6, 7.8], "active": True}
    for name, value in [("fruits.pkl", fruits), ("scores.pkl", scores), ("complex_data.pkl", complex_data)]:
        save_pickle(name, value)
        restored = load_pickle(name)
        assert restored == value, f"Round-trip mismatch in {name}"
        print(f"{name}: saved and loaded; equality = {restored == value}")
        print("  Loaded:", restored)

    print("\nPART 2: Custom GradeTracker object")
    tracker = GradeTracker("Introduction to Machine Learning")
    for name, grade in [("Alice", 95), ("Bob", 87), ("Charlie", 91), ("Diana", 84), ("Eve", 78)]:
        tracker.add_grade(name, grade)
    initial_average = tracker.get_average()
    save_pickle("ml_course_grades.pkl", tracker)
    restored_tracker = load_pickle("ml_course_grades.pkl")
    assert isinstance(restored_tracker, GradeTracker)
    assert restored_tracker.student_grades == tracker.student_grades
    assert restored_tracker.last_updated == tracker.last_updated
    print(restored_tracker)
    print("Loaded timestamp:", restored_tracker.last_updated.isoformat())
    print(f"Initial class average: {initial_average:.1f}")
    print("Top student:", restored_tracker.get_top_student())
    for name, grade in [("Frank", 89), ("Grace", 92), ("Hannah", 79)]:
        restored_tracker.add_grade(name, grade)
    save_pickle("ml_course_grades_updated.pkl", restored_tracker)
    updated_tracker = load_pickle("ml_course_grades_updated.pkl")
    assert len(updated_tracker.student_grades) == 8
    assert updated_tracker.student_grades == restored_tracker.student_grades
    print(f"Updated class average ({len(updated_tracker.student_grades)} students): {updated_tracker.get_average():.3f}")
    print("Top student after update:", updated_tracker.get_top_student())

    print("\nPART 3: scikit-learn LinearRegression with pickle")
    # Match the supplied tutorial's seed and 30-example synthetic-data recipe.
    np.random.seed(42)
    study_hours = np.random.uniform(1, 25, 30).reshape(-1, 1)
    test_scores = 50 + 2 * study_hours + np.random.normal(0, 5, 30).reshape(-1, 1)
    model = LinearRegression().fit(study_hours, test_scores)
    predictions = model.predict(study_hours)
    mse = float(mean_squared_error(test_scores, predictions))
    r2 = float(r2_score(test_scores, predictions))
    print(f"Coefficient: {model.coef_[0][0]:.6f}")
    print(f"Intercept: {model.intercept_[0]:.6f}")
    print(f"Training-set Mean Squared Error: {mse:.6f}")
    print(f"Training-set R-squared: {r2:.6f}")
    print("These are in-sample tutorial metrics, not held-out test results.")
    save_pickle("study_hours_model.pkl", model)
    loaded_model = load_pickle("study_hours_model.pkl")
    np.testing.assert_array_equal(predictions, loaded_model.predict(study_hours))
    hours = np.array([5, 10, 15, 20], dtype=float).reshape(-1, 1)
    new_predictions = loaded_model.predict(hours).ravel()
    print("Study hours | Predicted score")
    for hour, score in zip(hours.ravel(), new_predictions):
        print(f"{hour:11.1f} | {score:.1f}")
    print("Additional prediction-function examples:")
    extra = {}
    for hour in [12.5, 7.8, 22]:
        value = float(loaded_model.predict(np.array([[hour]]))[0, 0])
        extra[str(hour)] = value
        print(f"  {hour} hours -> {value:.1f}")

    fig, ax = plt.subplots(figsize=(9, 5.5))
    ax.scatter(study_hours.ravel(), test_scores.ravel(), color="#087E8B", label="Synthetic observations", s=45)
    order = np.argsort(study_hours.ravel())
    ax.plot(study_hours.ravel()[order], predictions.ravel()[order], color="#D35D36", linewidth=2, label="Linear regression fit")
    ax.set(xlabel="Study Hours per Week", ylabel="Test Score",
           title="Study Hours vs. Test Scores (Synthetic Tutorial Data)")
    ax.legend()
    ax.grid(alpha=0.25)
    fig.tight_layout()
    fig.savefig(ROOT / "study_hours_model.png", dpi=180)
    plt.close(fig)

    print("\nPART 4: joblib model persistence")
    joblib.dump(model, ROOT / "study_hours_model.joblib")
    joblib_model = joblib.load(ROOT / "study_hours_model.joblib")
    probe = np.array([[17.5]])
    pickle_prediction = float(loaded_model.predict(probe)[0, 0])
    joblib_prediction = float(joblib_model.predict(probe)[0, 0])
    np.testing.assert_array_equal(loaded_model.predict(hours), joblib_model.predict(hours))
    print(f"17.5 hours: pickle prediction = {pickle_prediction:.6f}")
    print(f"17.5 hours: joblib prediction = {joblib_prediction:.6f}")
    print("Predictions are identical:", pickle_prediction == joblib_prediction)

    results = {
        "student": {"name": "LanMingqi", "id": "26723811"},
        "versions": {"python": platform.python_version(), "numpy": np.__version__,
                     "scikit_learn": sklearn.__version__, "joblib": joblib.__version__,
                     "matplotlib": matplotlib.__version__},
        "part1_round_trip_equal": True,
        "grades": {"initial_count": 5, "initial_average": initial_average,
                   "updated_count": 8, "updated_average": updated_tracker.get_average(),
                   "top_student": list(updated_tracker.get_top_student())},
        "regression": {"seed": 42, "sample_count": 30, "coefficient": float(model.coef_[0][0]),
                       "intercept": float(model.intercept_[0]), "training_mse": mse, "training_r2": r2,
                       "metric_scope": "training observations; no held-out evaluation in the tutorial",
                       "predictions": [{"hours": float(h), "score": float(v)} for h, v in zip(hours.ravel(), new_predictions)],
                       "additional_predictions": extra},
        "pickle_joblib_equal": pickle_prediction == joblib_prediction,
    }
    (ROOT / "results.json").write_text(json.dumps(results, indent=2) + "\n", encoding="utf-8")
    names = ["fruits.pkl", "scores.pkl", "complex_data.pkl", "ml_course_grades.pkl",
             "ml_course_grades_updated.pkl", "study_hours_model.pkl", "study_hours_model.joblib"]
    manifest = {name: {"bytes": (ROOT / name).stat().st_size,
                      "sha256": hashlib.sha256((ROOT / name).read_bytes()).hexdigest()} for name in names}
    (ROOT / "artifact_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print("\nAll four parts completed; every saved file was loaded and checked.")


def main():
    buffer = io.StringIO()
    with contextlib.redirect_stdout(buffer):
        run()
    log = buffer.getvalue()
    (ROOT / "execution_log.txt").write_text(log, encoding="utf-8")
    print(log, end="")


if __name__ == "__main__":
    main()
